-- ════════════════════════════════════════════════════════════════════════════
-- ROW LEVEL SECURITY + OWNER POLICIES (idempotent, applied to every table)
-- ════════════════════════════════════════════════════════════════════════════
-- Each owner-scoped table gets a permissive policy:
--   user_id = auth.uid()  OR  user_id IS NULL   (legacy rows stay accessible)
-- A few tables use a different owner column (team_owner_id) and are handled too.

DO $$
DECLARE
  t TEXT;
  owner_col TEXT;
  owner_tables TEXT[] := ARRAY[
