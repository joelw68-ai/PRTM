--
-- WHAT THIS IS
--   ONE complete, idempotent SQL script that creates EVERY table and column the
--   app code references via supabase.from('...'). Safe to run as many times as
--   you like — every statement uses CREATE TABLE IF NOT EXISTS, ALTER TABLE ADD
--   COLUMN IF NOT EXISTS, or CREATE INDEX IF NOT EXISTS. Existing data is never
--   touched.
--
-- HOW TO RUN
--   Paste the whole file into the Supabase SQL Editor and press "Run" ONCE.
--   At the bottom it enables Row Level Security + an owner policy on every table
--   and refreshes the PostgREST schema cache.
--
-- COVERAGE
--   This was generated by scanning the entire codebase for every
--   supabase.from('<table>') reference and every column the app reads/writes.
--   It resolves the reported PGRST205 ("table not in schema cache") and 400
--   ("column does not exist") errors — including:
--     • maintenance_items.service_log / last_service_time / threshold
--     • tire_sets / tire_tread_depth / tire_pressure_history / tire_change_log
--     • maintenance_categories / maintenance_alert_settings /
--       maintenance_category_overrides
--     • team_activity_feed / pass_history / offline_queue / track_records
