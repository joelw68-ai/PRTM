    IF t = 'audit_logs' THEN
      EXECUTE format(
        'CREATE POLICY %I ON public.%I FOR ALL USING (user_id = auth.uid()::text OR user_id IS NULL) WITH CHECK (user_id = auth.uid()::text OR user_id IS NULL);',
        t || '_owner', t);
    ELSE
      EXECUTE format(
        'CREATE POLICY %I ON public.%I FOR ALL USING (user_id = auth.uid() OR user_id IS NULL) WITH CHECK (user_id = auth.uid() OR user_id IS NULL);',
        t || '_owner', t);
    END IF;
  END LOOP;

