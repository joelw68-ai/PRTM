    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL USING (%I = auth.uid() OR %I IS NULL) WITH CHECK (%I = auth.uid() OR %I IS NULL);',
      t || '_owner', t, owner_col, owner_col, owner_col, owner_col);
  END LOOP;
